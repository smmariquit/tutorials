export function getTalkImage(talk) {
  return talk.actionPhoto || talk.slidesThumbnail;
}

export function getTalkUrl(slug) {
  return `${PORTFOLIO_URL}/talks/${slug}`;
}

export function getTotalAudience() {
  return talks.reduce((sum, talk) => sum + (talk.audienceSize || 0), 0);
}

export function sortTalksByDate(list = talks) {
  return [...list].sort((a, b) => {
    const aTime = a.date ? new Date(a.date).getTime() : 0;
    const bTime = b.date ? new Date(b.date).getTime() : 0;
    return bTime - aTime;
  });
}

export function formatTalkDate(date) {
  if (!date) return '';
  return new Date(date).toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
  });
}
